missing_stats = []

for path in las_paths:

    well_name = os.path.basename(path).replace(".las", "")

    try:
        las_temp = lasio.read(path)
        df_temp = las_temp.df()

        for column in df_temp.columns:

            missing_count = df_temp[column].isna().sum()
            total_count = len(df_temp)

            missing_stats.append({
                "WELL": well_name,
                "LOG": column,
                "MISSING_COUNT": missing_count,
                "TOTAL_SAMPLES": total_count,
                "MISSING_PERCENTAGE": (
                    missing_count / total_count * 100
                )
            })

    except Exception as e:
        print("Error reading:", well_name)
        print(e)

