lithology_map = {
    0: "Sandstone",
    1: "Shale",
    2: "Sandstone/Shale",
    3: "Limestone",
    4: "Chalk",
    5: "Dolomite",
    6: "Marl",
    9: "Tuff",
    11: "Class 11"
}

# ------------------------------------------------------------
# Function to generate error pairs
# ------------------------------------------------------------

def get_error_pairs(y_true, y_pred):

    error_df = pd.DataFrame({
        "ACTUAL": np.asarray(y_true),
        "PREDICTED": np.asarray(y_pred)
    })

    error_df = error_df[
        error_df["ACTUAL"] != error_df["PREDICTED"]
    ].copy()

    pair_counts = (
        error_df
        .groupby(["ACTUAL", "PREDICTED"])
        .size()
        .reset_index(name="MISCLASSIFIED_SAMPLES")
        .sort_values(
            "MISCLASSIFIED_SAMPLES",
            ascending=False
        )
        .reset_index(drop=True)
    )

    pair_counts["ACTUAL_LITHOLOGY"] = (
        pair_counts["ACTUAL"].map(lithology_map)
        .fillna("Unknown")
    )

    pair_counts["PREDICTED_LITHOLOGY"] = (
        pair_counts["PREDICTED"].map(lithology_map)
        .fillna("Unknown")
    )

    total_errors = pair_counts["MISCLASSIFIED_SAMPLES"].sum()

    pair_counts["ERROR_SHARE_%"] = (
        pair_counts["MISCLASSIFIED_SAMPLES"]
        / total_errors
        * 100
    )

    return pair_counts[
        [
            "ACTUAL",
            "PREDICTED",
            "ACTUAL_LITHOLOGY",
            "PREDICTED_LITHOLOGY",
            "MISCLASSIFIED_SAMPLES",
            "ERROR_SHARE_%"
        ]
    ]


