features_to_check = ["RHOB", "NPHI"]

for path in las_paths:

    well_name = os.path.basename(path).replace(".las", "")

    # Only use our 117 modelling wells
    if well_name not in set(ml_dataset["WELL"].unique()):
        continue

    try:
        las_temp = lasio.read(path)
        df_temp = las_temp.df().reset_index()

        # Keep only labelled samples
        df_temp = df_temp[
            df_temp[target_col].notna()
        ].copy()

        if len(df_temp) == 0:
            continue

        # Sort by depth
        df_temp = df_temp.sort_values("DEPT").reset_index(drop=True)

        for feature in features_to_check:

            if feature not in df_temp.columns:
                continue

            missing = df_temp[feature].isna()

            # Identify consecutive missing groups
            group_id = (
                missing != missing.shift()
            ).cumsum()

            for gid, group in df_temp.groupby(group_id):

                if not missing.loc[group.index[0]]:
                    continue

                start_depth = group["DEPT"].iloc[0]
                end_depth = group["DEPT"].iloc[-1]

                gap_records.append({
                    "WELL": well_name,
                    "FEATURE": feature,
                    "START_DEPTH": start_depth,
                    "END_DEPTH": end_depth,
                    "MISSING_SAMPLES": len(group),
                    "GAP_LENGTH_M":
                        end_depth - start_depth
                })

    except Exception as e:
        print("Error:", well_name, e)

